// Обезличивание текста перед отправкой в ИИ.
// Работает на телефоне: из текста вырезается всё, по чему можно понять, чей это документ, —
// ФИО, дата рождения, возраст, адрес, телефон, почта, номера полиса, СНИЛС, паспорта, карты и заказа, подписи врачей.
// В ИИ уходит только сама медицинская часть: названия показателей, значения, нормы, заключение.
// Тот же код стоит в функции на сервере — вторым слоем защиты.
(function (root) {
  const MARK = '[скрыто]';
  // Поля, значение которых целиком убираем до конца строки или до следующей колонки бланка
  const LABELS = [
    'ф\\.?\\s?и\\.?\\s?о\\.?', 'пациент(?:ка|а)?', 'фамилия', 'имя', 'отчество', 'пол', 'дата\\s+рожд[а-яёa-z]*', 'д\\.\\s?р\\.', 'г\\.\\s?р\\.', 'год\\s+рожд[а-яёa-z]*',
    'возраст', 'адрес[а-яёa-z]*', 'место\\s+жительства', 'прописка', 'телефон[а-яёa-z]*', 'тел\\.', 'моб\\.', 'e-?mail', 'эл\\.?\\s*почта',
    'полис[а-яёa-z]*', 'омс', 'дмс', 'снилс', 'паспорт[а-яёa-z]*', 'инн', 'страхов[а-яёa-z]+\\s+компан[а-яёa-z]*',
    '(?:№|номер)\\s*(?:мед[а-яёa-z]*\\s+)?карты', 'мед[а-яёa-z]*\\s+карт[а-яёa-z]*', 'амб[а-яёa-z]*\\s+карт[а-яёa-z]*', 'карта\\s+пациента', 'история\\s+болезни',
    '(?:№|номер)\\s*(?:заказа|заявки|образца|пробы|направления|исследования)', 'заказ\\s*№', 'заявка\\s*№', 'инз', 'штрих-?код', 'баркод', 'id\\s+пациента', 'код\\s+пациента',
    'лечащий\\s+врач', 'направивший\\s+врач', 'врач(?:-[а-яё]+)?', 'исследование\\s+(?:провел|провела|выполнил|выполнила)[а-яёa-z]*', 'выполнил[а-яёa-z]*', 'провел[а-яёa-z]*', 'проверил[а-яёa-z]*', 'одобрил[а-яёa-z]*', 'утвердил[а-яёa-z]*', 'направил[а-яёa-z]*', 'подпись', 'м\\.?п\\.',
    'владелец', 'хозяин[а-яёa-z]*', 'клиент', 'кличка'
  ];
  const LABEL_RE = new RegExp('(^|[\\s|;,(])(' + LABELS.join('|') + ')(\\s*[:№#]\\s*|\\s{1,3}(?=\\S))([^\\n|;]*?)(?=\\s{2,}|\\t|\\s\\|\\s|;|$)', 'gimu');

  const RULES = [
    [/[\w.+-]+@[\w-]+\.[\w.-]+/g, MARK],                                                   // почта
    [/(?:\+7|(?<!\d)8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?!\d)/g, MARK],       // телефон
    [/(?<!\d)\d{3}-\d{3}-\d{3}[\s-]\d{2}(?!\d)/g, MARK],                                    // СНИЛС
    [/(?<!\d)\d{2}\s?\d{2}\s?№?\s?\d{6}(?!\d)/g, MARK],                                     // паспорт
    [/(?<![\d.,])\d{9,}(?![\d.,])/g, MARK],                                                 // полис, штрихкод, номер заказа
    [/(?<![\d.,])(?:\d{4}\s){3,}\d{4}(?!\d)/g, MARK],                                       // номер полиса группами
    // ФИО с отчеством: Иванова Мария Евгеньевна / Мария Евгеньевна Иванова
    [/[А-ЯЁ][а-яё-]+\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+(?:ович|евич|ьевич|ич|овна|евна|ьевна|ична|инична)(?![а-яё])/gu, MARK],
    [/[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+(?:ович|евич|ьевич|овна|евна|ьевна|ична|инична)(?:\s+[А-ЯЁ][а-яё-]+)?(?![а-яё])/gu, MARK],
    // Фамилия с инициалами: Иванова М.Е. / М.Е. Иванова
    [/[А-ЯЁ][а-яё-]{1,}\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.?/gu, MARK],
    [/(?<![А-ЯЁа-яё])[А-ЯЁ]\.\s?[А-ЯЁ]\.\s?[А-ЯЁ][а-яё-]{1,}/gu, MARK],
    // Адрес
    [/(?:г\.\s?[А-ЯЁ][а-яё-]+,?\s*)?(?:ул\.|улица|пр-т|просп\.|проспект|пер\.|переулок|ш\.|шоссе|наб\.|набережная|б-р|бульвар|пл\.|площадь|мкр\.?)\s+[^\n;]{1,60}?(?:д\.|дом)\s*\d+[^\n;]{0,25}/giu, MARK],
    [/(?:кв\.|квартира|корп\.|корпус|стр\.\s?\d)\s*\d+/giu, MARK]
  ];

  function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

  // Имена из профилей и врачей: убираем со всеми окончаниями (Мария, Марии, Марию)
  function namesRe(names) {
    const stems = [...new Set((names || []).flatMap(n => String(n || '').split(/\s+/)).map(w => w.trim()).filter(w => w.length >= 3 && /^[А-ЯЁA-Z]/i.test(w))
      .map(w => w.length > 4 ? w.slice(0, -1) : w))];
    if (!stems.length) return null;
    return new RegExp('(?<![А-ЯЁа-яёA-Za-z])(' + stems.map(escapeRe).join('|') + ')[а-яёa-z]{0,3}(?![А-ЯЁа-яёA-Za-z])', 'giu');
  }

  function scrub(text, opts = {}) {
    let s = String(text || ''), n = 0;
    const count = m => { n++; return m; };
    s = s.replace(LABEL_RE, (all, pre, label, sep, val) => {
      if (!val.trim()) return all;
      // «Пол» в бланке бывает и показателем — убираем только короткое значение м/ж
      if (/^пол$/i.test(label) && !/^(м|ж|муж\w*|жен\w*|male|female)\.?$/i.test(val.trim())) return all;
      n++; return pre + label + sep + MARK;
    });
    for (const [re, to] of RULES) s = s.replace(re, () => { n++; return to; });
    const nr = namesRe(opts.names);
    if (nr) s = s.replace(nr, () => { n++; return MARK; });
    s = s.replace(/(?:\[скрыто\][ \t,.]*){2,}/g, MARK + ' ');
    return { text: s, removed: n };
  }

  const api = { scrub, MARK };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.Anon = api;
})(typeof self !== 'undefined' ? self : this);
